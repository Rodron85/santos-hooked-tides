#!/usr/bin/env python3
"""Copies the shared engine (moon, tides, best times, fish, spots, rules, Portuguese words) from the phone
app (public/index.html) into watch/js/shared.js, so the watch works out everything the same way.

Only READS public/index.html: the phone app is never changed.
Run from the repo root after changing the phone app:  python3 watch/tools/extract.py
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = (ROOT / 'public' / 'index.html').read_text(encoding='utf-8').split('\n')
OUT = ROOT / 'watch' / 'js' / 'shared.js'

# (start marker, end marker): copy from the line with start up to (not including) the line with end
BLOCKS = [
    ('let LAT = 50.9097', '// ---------- rendering helpers'),          # astronomy, UK time, tide models, day model
    ('// ---------- rendering helpers', '// ---------- location ----------'),  # moon names, fish (UK), spots
    ('// ---------- location ----------', "let gpsMsg = ''"),        # location and region
    ('const DATUM', 'async function getJSON'),                         # live data store, Admiralty tides
    ('const COMPASS = ', 'function renderLiveBits'),                   # wind words, sea state
    ('function dailyWx', '// ---------- catch log'),                  # daily weather, pressure, warnings region, water clarity
    ('// ---------- day rating with weather', 'function renderBest'),  # day rating, tide phase, best windows
    ('// ---------- target species', 'function renderTarget'),          # target species
    ('// ---------- Portugal & Madeira pack', 'function rulesPT'),     # Portugal & Madeira fish, places
    ('// ---------- language (English', 'const TR_ATTRS'),            # Portuguese words
]

def find(marker, start=0):
    for i in range(start, len(SRC)):
        if marker in SRC[i]:
            return i
    sys.exit(f'Marker not found in public/index.html: {marker!r}')

PRELUDE = '''// GENERATED by watch/tools/extract.py from public/index.html (the phone app). Do not edit by hand.
// Same maths and data as the phone app; the watch screens are in app.js.
if (!Array.prototype.flat) Array.prototype.flat = function (d) { d = d === undefined ? 1 : d; return d > 0 ? this.reduce((a, v) => a.concat(Array.isArray(v) ? v.flat(d - 1) : v), []) : this.slice(); };
if (!Array.prototype.flatMap) Array.prototype.flatMap = function (f, t) { return this.map(f, t).flat(1); };
const $ = () => null; // the phone app's page elements don't exist on the watch
'''
POSTLUDE = '''
// ---------- state (the watch keeps "now" fresh) ----------
let now = Date.now(), tp = ukParts(now);
function tick() { now = Date.now(); tp = ukParts(now); }
const isToday = s => s.y === tp.y && s.m === tp.m && s.d === tp.d;
const addDays = (s, n) => { const x = new Date(Date.UTC(s.y, s.m, s.d + n)); return { y: x.getUTCFullYear(), m: x.getUTCMonth(), d: x.getUTCDate(), dow: x.getUTCDay() }; };
'''

parts, pos = [PRELUDE], 0
for a, b in BLOCKS:
    i = find(a, pos); j = find(b, i + 1)
    parts.append(f'// ===== from the phone app: {a} =====')
    parts.append('\n'.join(l[2:] if l.startswith('  ') else l for l in SRC[i:j]))
    pos = j
parts.append(POSTLUDE)
OUT.write_text('\n'.join(parts), encoding='utf-8')
print(f'wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)')
